import {readFileSync, writeFileSync, mkdirSync} from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const ext = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const catalog = JSON.parse(readFileSync(path.join(ext, 'template-catalog.json'), 'utf8'));
const localized = JSON.parse(readFileSync(path.join(ext, 'src/template-gallery/chinese-props.json'), 'utf8'));
const items = catalog.compositions;
const labelFor = c => c.composition_id === 'bounce-in-headline' ? '标题弹入' : c.name_zh;
if (items.length !== 55 || new Set(items.map(c => c.composition_id)).size !== 55) throw new Error('Expected exactly 55 unique registered compositions.');
const imports = [], entries = [];
for (const [i, c] of items.entries()) {
  if (!(c.composition_id in localized)) throw new Error(`Missing Chinese parameters: ${c.composition_id}`);
  const base = c.base_composition_id ? items.find(x => x.composition_id === c.base_composition_id) : c;
  let source, component, defaults;
  if (c.composition_id === 'library-orbit' || c.composition_id === 'library-text-mask') {
    source = '../template-library/remotion-ui/Demos';
    component = c.composition_id === 'library-orbit' ? 'OrbitMotionDemo' : 'TextMaskVideoDemo';
    defaults = c.composition_id === 'library-orbit' ? 'orbitMotionDemoDefaults' : 'textMaskVideoDemoDefaults';
  } else {
    source = '../' + base.source_path.replace(/^src\//, '').replace(/\.tsx$/, '');
    component = base.component_export; defaults = base.default_props_export;
  }
  imports.push(`import {${component} as C${i}, ${defaults} as D${i}} from ${JSON.stringify(source)};`);
  entries.push(`{id:${JSON.stringify(c.composition_id)}, label:${JSON.stringify(labelFor(c))}, Component:C${i}, props:{...D${i},...localized[${JSON.stringify(c.composition_id)}]}, width:${c.width}, height:${c.height}, fps:${c.fps}, frames:${c.duration_frames}}`);
}
const root = `// Generated by gallery-tools/prepare-gallery.mjs. Independent entry; original Root untouched.
import React, {useEffect, useState} from 'react';
import {AbsoluteFill, Composition, continueRender, delayRender, staticFile} from 'remotion';
import localized from './chinese-props.json';
${imports.join('\n')}
const items = [${entries.join(',\n')}];
const Shell: React.FC<{children:React.ReactNode; label:string}> = ({children,label}) => {
 const [handle] = useState(() => delayRender('Wait for Chinese gallery font'));
 useEffect(() => {document.fonts.load('700 40px TemplateNoto').then(() => continueRender(handle));}, [handle]);
 return <AbsoluteFill><style>{\`@font-face{font-family:TemplateNoto;src:url('\${staticFile('NotoSansSC.ttf')}') format('truetype');font-weight:100 900;} *{font-family:TemplateNoto,sans-serif!important;}\`}</style>{children}<div style={{position:'absolute',left:20,top:16,padding:'7px 14px',borderRadius:8,background:'#102b36dd',color:'#f2f8fa',fontSize:22,lineHeight:1.4,fontWeight:700,zIndex:1000}}>{label} · 中文示意</div></AbsoluteFill>;
};
const wrapped = items.map(item=>({...item, Wrapped:(props:Record<string,unknown>)=><Shell label={item.label}>{React.createElement(item.Component as React.ComponentType<Record<string,unknown>>,props)}</Shell>}));
export const GalleryRoot = () => <>{wrapped.map(item=><Composition key={item.id} id={item.id} component={item.Wrapped} defaultProps={item.props} width={item.width} height={item.height} fps={item.fps} durationInFrames={item.frames}/>)}</>;
`;
mkdirSync(path.join(ext, 'src/template-gallery'), {recursive: true});
writeFileSync(path.join(ext, 'src/template-gallery/GalleryRoot.tsx'), root);
writeFileSync(path.join(ext, 'src/template-gallery/index.ts'), "import {registerRoot} from 'remotion';\nimport {GalleryRoot} from './GalleryRoot';\nregisterRoot(GalleryRoot);\n");
console.log(JSON.stringify({registered:items.length, entry:'src/template-gallery/index.ts', vendor_changed:false}));
