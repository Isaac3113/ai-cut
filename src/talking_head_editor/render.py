def global_caption_themes(plan, clips):
    """Map appearance only; subtitle words/timing still use the main clips."""
    by_id={c['id']:c for c in clips}
    return [{'start':by_id[o['clip_id']]['output_start']+o['offset']/by_id[o['clip_id']]['playback_speed'],
             'end':by_id[o['clip_id']]['output_start']+(o['offset']+o['duration'])/by_id[o['clip_id']]['playback_speed'],
             'theme':'dark'} for o in plan.get('overlays',[])
            if o.get('caption_theme')=='dark' and o['clip_id'] in by_id]

def cache_valid(path, key):
    receipt = Path(str(path) + ".json")
    if path.is_file() and receipt.is_file():
        saved = read_json(receipt)
        return saved.get("key") == key and saved.get("sha256") == file_hash(path)
    return False


def seal(path, key):
    require(path.is_file() and path.stat().st_size > 0, "render_missing", "Renderer produced no file")
    probe(path)
    decoded = False
    if path.suffix.lower() == '.mp4':
        run([executable('ffmpeg'),'-v','error','-xerror','-threads','1','-i',path,'-f','null','-'],
            timeout=180,log=path.parent/'seal-decode.log')
        decoded = True
    atomic_json(str(path)+".json", {"key": key, "sha256": file_hash(path),"full_decode_pass":decoded})


def ff(args, cwd, name, timeout=3600):
    return run([executable("ffmpeg"), "-y", "-nostdin", "-hide_banner", "-threads", "2",
                "-filter_complex_threads", "1", *args], cwd=cwd, timeout=timeout,
               log=Path(cwd)/f"{name}.log")


def filter_path(path):
    return str(path).replace("\\", "/").replace(":", r"\:").replace("'", r"'\''")


def concatenate(paths, target, work, audio=False):
    # Paths generated by us may contain spaces; ffconcat has its own quote grammar.
    lines = ["file '"+str(p.resolve()).replace("\\", "/").replace("'", "'\\''")+"'" for p in paths]
    listing = work / ("audio-concat.txt" if audio else "video-concat.txt")
    listing.write_text("\n".join(lines), encoding="utf-8")
    options=[] if audio else ["-video_track_timescale","90000","-movie_timescale","90000"]
    ff(["-f", "concat", "-safe", "0", "-i", listing, "-c", "copy", *options, target], work, "concat-audio" if audio else "concat-video")


def render_audio(job, project, clips, style):
    """Master speech once, then mix independent music. Never normalize the mix."""
    import shutil
    plan = project["plan"]
    music = project["assets"].get(plan.get("music_asset_id"))
    signature = {"engine": __version__, "source": project["source"]["sha256"],
                 "clips": [(c["start"], c["end"], c["frames"], c["playback_speed"]) for c in clips],
                 "music": music["sha256"] if music else None,
                 "style": {k:style[k] for k in ("music_gain_db","loudness_lufs","true_peak_db")}}
    key = digest(signature)
    work = job / "cache" / "audio" / key
    work.mkdir(parents=True, exist_ok=True)
    target = work / "mix.wav"
    voice_key = digest({"voice_pipeline":2,"source":signature['source'],"clips":signature['clips'],
                        "loudness_lufs":style['loudness_lufs'],"true_peak_db":style['true_peak_db']})
    voice_work = job/'cache'/'voice'/voice_key
    voice_work.mkdir(parents=True,exist_ok=True)
    voice = voice_work/'voice.wav'
    music_track = work/'music-only.wav'
    if cache_valid(target, key) and cache_valid(voice,voice_key) and (not music or cache_valid(music_track,key+'-music')):
        return target, True
    source = inside(job, project["source"]["path"])
    duration = sum(c["output_duration"] for c in clips)
    if not cache_valid(voice,voice_key):
        parts = []
        for i,c in enumerate(clips):
            part = voice_work / f"part{i:04d}.wav"
            partkey = digest({"source": signature["source"], "start":c["start"], "end":c["end"], "frames":c["frames"], "speed":c["playback_speed"]})
            if not cache_valid(part, partkey):
                length = c["output_duration"]
                filt = (f"atempo={c['playback_speed']},apad,atrim=duration={length:.9f},asetpts=PTS-STARTPTS,"
                        f"afade=t=in:d=0.004,afade=t=out:st={max(0,length-.004):.9f}:d=0.004")
                ff(["-ss", c["start"], "-t", c["end"]-c["start"], "-i", source,
                    "-vn", "-af", filt, "-ar", "48000", "-ac", "2", "-c:a", "pcm_s16le", part], voice_work, f"part{i:04d}")
                seal(part, partkey)
            parts.append(part)
        speech = voice_work / "speech.wav"
        concatenate(parts, speech, voice_work, audio=True)
        norm = f"loudnorm=I={style['loudness_lufs']}:TP={style['true_peak_db']}:LRA=11"
        _, statslog = ff(["-i", speech, "-af", norm+":print_format=json", "-f", "null", "-"], voice_work, "loudness-measure")
        matches = re.findall(r'\{\s*"input_i"[\s\S]*?\}', statslog)
        require(matches, "loudness_missing", "No speech loudness measurement returned")
        stats = json.loads(matches[-1])
        require(all(math.isfinite(float(stats[k])) for k in ("input_i","input_tp","input_lra","input_thresh","target_offset")),
                "silent_audio", "Speech is silent or not measurable; inspect source")
        second = norm + (f":measured_I={stats['input_i']}:measured_TP={stats['input_tp']}"
                         f":measured_LRA={stats['input_lra']}:measured_thresh={stats['input_thresh']}"
                         f":offset={stats['target_offset']}:linear=true")
        ff(["-i", speech, "-af", second, "-ar", "48000", "-ac", "2", "-c:a", "pcm_s16le", voice], voice_work, "loudness-apply")
        seal(voice,voice_key)
    if music:
        musicfilter = (f"[1:a]loudnorm=I=-18:TP=-2:LRA=11,volume={style['music_gain_db']}dB,"
                     f"afade=t=in:d=0.8,afade=t=out:st={max(0,duration-1.5)}:d=1.5[bg];"
                     "[bg][0:a]sidechaincompress=threshold=0.04:ratio=8:attack=20:release=300[duck]")
        ff(["-i", voice, "-stream_loop", "-1", "-i", inside(job,music["path"]),
            "-filter_complex", musicfilter, "-map", "[duck]", "-t", duration,
            "-ar", "48000", "-ac", "2", "-c:a", "pcm_f32le", music_track], work, "music")
        seal(music_track,key+'-music')
        ff(['-i',voice,'-i',music_track,'-filter_complex','[0:a][1:a]amix=inputs=2:duration=first:normalize=0[out]',
            '-map','[out]','-t',duration,'-ar',48000,'-ac',2,'-c:a','pcm_s16le',target],work,'music-mix')
    else:
        shutil.copyfile(voice,target)
    atomic_json(work/'audio-stems.json',{'voice':voice.relative_to(job).as_posix(),'voice_sha256':file_hash(voice),
        'music':music_track.relative_to(job).as_posix() if music else None,
        'music_sha256':file_hash(music_track) if music else None,'duration':duration,
        'pipeline':'speech mastering -> independent music ducking -> additive mix',
        'post_mix_loudness_normalization':False})
    seal(target, key)
    return target, False


def framing_filters(layout, width, height, style, speed=1):
    """Preserve the foreground; blur is an explicit opt-in for contain layouts."""
    finish = f"setsar=1,fps={FPS},tpad=stop_mode=clone:stop_duration=0.1[base]"
    fit = layout.get("fit", "contain")
    if fit == "contain" and layout.get("background") == "blur":
        radius = max(1, round(min(width, height) / 30))
        return [
            f"[0:v]setpts=(PTS-STARTPTS)/{speed},split=2[foreground][backdrop]",
            f"[backdrop]scale={width}:{height}:force_original_aspect_ratio=increase,"
            f"crop={width}:{height},boxblur=luma_radius={radius}:luma_power=2:"
            f"chroma_radius={max(1, radius//2)}:chroma_power=2,"
            "eq=brightness=-0.14:saturation=0.8,setsar=1[blurred]",
            f"[foreground]scale={width}:{height}:force_original_aspect_ratio=decrease,setsar=1[contained]",
            f"[blurred][contained]overlay=x=(W-w)/2:y=(H-h)/2,{finish}",
        ]
    if fit == "cover":
        framing = f"scale={width}:{height}:force_original_aspect_ratio=increase,crop={width}:{height}:(iw-ow)*{layout.get('x',.5)}:(ih-oh)*{layout.get('y',.5)}"
    else:
        framing = f"scale={width}:{height}:force_original_aspect_ratio=decrease,pad={width}:{height}:(ow-iw)/2:(oh-ih)/2:color={style['background']}"
    return [f"[0:v]setpts=(PTS-STARTPTS)/{speed},{framing},{finish}"]


def portrait_title_image(title, path, width, height, source_info, style):
    """Fit a maximum of two title lines wholly inside the upper letterbox space."""
    stream = next((s for s in source_info.get("streams", []) if s.get("codec_type") == "video"), {})
    sw, sh = stream.get("width", 0), stream.get("height", 0)
    require(sw > 0 and sh > 0, "layout_title_space", "Source geometry is required for title placement")
    rotation = next((s["rotation"] for s in stream.get("side_data_list", []) if "rotation" in s),
                    stream.get("tags", {}).get("rotate", 0))
    if abs(round(float(rotation))) % 180 == 90:
        sw, sh = sh, sw
    # Match the existing contain scale and center placement. Reserve extra pixels
    # for FFmpeg rounding so title pixels never overlap the sharp foreground.
    foreground_height = min(height, width * sh / sw)
    gap = max(0, math.floor((height - foreground_height) / 2) - 2)
    margin = max(12, round(width * .045))
    require(gap > 2 * margin + 20, "layout_title_space",
            "Not enough upper letterbox space for a title; omit it or use a separate graphic")
    for size in range(round(width * .074), max(15, round(width * .04)) - 1, -1):
        face = font(size)
        lines = wrap(title.strip(), face, width - 2 * margin)
        line_height = math.ceil(size * 1.45)
        block_height = len(lines) * line_height
        if len(lines) <= 2 and block_height <= gap - 2 * margin:
            break
    else:
        require(False, "layout_title_overflow", "Shorten the layout title to fit two readable lines")
    strip = Image.new("RGBA", (width, gap), (0, 0, 0, 0))
    draw = ImageDraw.Draw(strip)
    top = (gap - block_height) // 2
    for i, line in enumerate(lines):
        draw.text(((width - face.getlength(line)) / 2, top + i * line_height), line,
                  font=face, anchor="lt", fill=style["caption_color"],
                  stroke_width=max(1, round(width / 270)), stroke_fill=style["background"])
    strip.save(path)
    return {"foreground_top": gap + 2, "title_bounds": strip.getbbox(), "lines": lines}


def render_clip(job, project, clip, all_words, aspect, style, scale, dimensions=None, *, include_ending=True):
    width, height = [round(v*scale/2)*2 for v in (dimensions or FORMATS[aspect])]
    speed = clip.get("playback_speed", 1)
    overlays = [o for o in project["plan"].get("overlays", []) if o["clip_id"] == clip["id"]
                and o["offset"] < clip["end"]-clip["start"]]
    overlays = [dict(o, duration=min(o["duration"], clip["end"]-clip["start"]-o["offset"])) for o in overlays]
    effects = [e for e in project["plan"].get("visual_effects", []) if e["clip_id"] == clip["id"] and e["offset"] < clip["end"]-clip["start"]]
    expanded = []
    for o in overlays:
        graphic = o.get("graphic", {})
        times = graphic.get("step_times")
        if times:
            for step, at in enumerate(times):
                if at >= o["duration"]: break
                end = min(o["duration"], times[step+1] if step+1<len(times) else o["duration"])
                expanded.append({**o,"offset":o["offset"]+at,"duration":end-at,
                                 "graphic":{**graphic,"visible_count":step+1,"active_index":step},"continuous_step":True})
        else: expanded.append(o)
    overlays = expanded
    require(len(overlays) <= 32, "overlay_limit", "Split the clip before using more than 32 expanded overlays")
    words = [dict(w, start=w["start"]-clip["output_start"], end=w["end"]-clip["output_start"])
             for w in all_words if w["clip_id"] == clip["id"]]
    signature = {"engine":VIDEO_PIPELINE_REVISION, "source":project["source"]["sha256"], "clip":clip,
                 "words":words,"overlays":overlays,"visual_effects":effects,"assets":{o['asset_id']:project['assets'][o['asset_id']]['sha256'] for o in overlays if o.get('asset_id')},
                 "style":style,"aspect":aspect,"scale":scale,"dimensions":[width,height], "font_sha256": file_hash(font_path())}
    if include_ending and any(continues_into_ending(o, clip, project["plan"]) for o in overlays):
        signature["ending_continuation"] = {"revision":CONTINUOUS_ENDING_REVISION,"asset":project["plan"]["ending"]}
    # Source order affects subtitle timing globally, but clip-local cache stays reusable.
    signature["clip"] = {k:v for k,v in clip.items() if k != "output_start"}
    key = digest(signature)
    work = job / "cache" / "video" / key
    work.mkdir(parents=True, exist_ok=True)
    target = work / "clip.mp4"
    if cache_valid(target, key):
        return target, True
    cues = caption_cues(words, width, height, style, scale)
    themes=[{'start':o['offset']/speed,'end':(o['offset']+o['duration'])/speed,'theme':o['caption_theme']}
            for o in overlays if o.get('caption_theme')=='dark']
    write_captions(work, cues, width, height, style, scale,theme_ranges=themes)
    append_keywords(work/"captions.ass", effects, speed, width, height, scale)
    atomic_json(work/"captions.json", cues)
    source = inside(job, project["source"]["path"])
    args = ["-ss", clip["start"], "-t", clip["end"]-clip["start"], "-threads", "1", "-i", source]
    layout = clip.get("layouts", {}).get(aspect, {})
    filters = framing_filters(layout, width, height, style, speed)
    previous = "base"
    presenter_zoom = punch_filter(effects, speed, width, height, layer="presenter")
    if presenter_zoom:
        filters.append(f"[base]{presenter_zoom}[presenter]")
        previous = "presenter"
    title_input = 0
    if layout.get("title"):
        media = work / "layout-title.png"
        bounds = portrait_title_image(layout["title"], media, width, height, project["source"]["probe"], style)
        atomic_json(work / "layout-title.json", bounds)
        args += ["-loop", "1", "-threads", "1", "-i", media]
        filters.append(f"[{previous}][1:v]overlay=x=0:y=0:eof_action=repeat[titled]")
        previous, title_input = "titled", 1
    for i, o in enumerate(overlays, 1):
        pip = o.get("mode") == "pip"
        banner = o.get("mode") == "banner"
        ow, oh = (int(width*.42)//2*2, int(height*.30)//2*2) if pip else ((int(width*.52)//2*2,int(height*.16)//2*2) if banner else (width,height))
        if o.get("asset_id"):
            asset = project["assets"][o["asset_id"]]
            media = inside(job, asset["path"])
            if asset["kind"] == "image":
                args += ["-loop", "1", "-threads", "1", "-i", media]
            else:
                args += ["-ss", o.get("source_start",0), "-t", o["duration"]/speed*o.get("asset_speed",speed), "-threads", "1", "-i", media]
        else:
            media = work / f"graphic{i}.png"
            graphic_image(o["graphic"], media, ow, oh, style)
            args += ["-loop", "1", "-threads", "1", "-i", media]
        span, offset = o["duration"]/speed, o["offset"]/speed
        fade = 0 if o.get("continuous_step") else min(.18,span/4)
        fade_out = "" if include_ending and continues_into_ending(o, clip, project["plan"]) else f"fade=t=out:st={span-fade}:d={fade}:alpha=1,"
        asset_speed = o.get("asset_speed", speed)
        filters.append(f"[{i+title_input}:v]trim=duration={span*asset_speed},setpts=(PTS-STARTPTS)/{asset_speed},scale={ow}:{oh}:force_original_aspect_ratio=decrease,"
                       f"pad={ow}:{oh}:(ow-iw)/2:(oh-ih)/2:color={style['background']},format=rgba,"
                       f"fade=t=in:st=0:d={fade}:alpha=1,{fade_out}"
                       f"setpts=PTS+{offset}/TB[ov{i}]")
        x, y = (f"W-w-{round(36*scale)}", str(round(48*scale))) if pip else ("0","0")
        if banner: x,y = str(round(60*scale)),str(round(height*.63))
        if o.get("continuous_step"):
            filters[-1] = filters[-1].replace(f"fade=t=in:st=0:d={fade}:alpha=1,{fade_out}", "")
        filters.append(f"[{previous}][ov{i}]overlay=x={x}:y={y}:eof_action=pass:enable='gte(t,{offset})*lt(t,{offset+span})'[v{i}]")
        previous = f"v{i}"
    zoom = punch_filter(effects, speed, width, height, layer="scene")
    if zoom:
        filters.append(f"[{previous}]{zoom}[motion]")
        previous = "motion"
    if cues or any(e["kind"] == "keyword" for e in effects):
        filters.append(f"[{previous}]subtitles=filename='captions.ass':fontsdir='{filter_path(render_font_dir())}'[out]")
    else:
        filters.append(f"[{previous}]null[out]")
    script = work / "filters.txt"
    script.write_text(";\n".join(filters), encoding="utf-8")
    args += ["-filter_complex", ";\n".join(filters), "-map", "[out]", "-frames:v", clip["frames"],
             "-an", "-c:v", "libx264", "-threads", "2", "-preset", "veryfast", "-crf", "18",
             "-pix_fmt", "yuv420p", "-r", FPS, "-video_track_timescale", "90000", "-movie_timescale", "90000", target]
    ff(args, work, "render", timeout=max(120,int(clip['output_duration']*20)))
    seal(target, key)
    return target, False


def preview_plan(clips, words, maximum=45, speed=1):
    selected, remaining = [], maximum*speed
    for c in clips:
        c = copy.deepcopy(c)
        span = c["end"]-c["start"]
        if span > remaining:
            ends = [w["end"] for w in words if c["start"] < w["end"] <= c["start"]+remaining-.08]
            if ends:
                c["end"] = min(c["end"], max(ends)+.08)
            else:
                c["end"] = c["start"]+remaining
        if c["end"]-c["start"] >= .1:
            selected.append(c)
        remaining -= c["end"]-c["start"]
        if remaining < .1:
            break
    return compile_clips(selected, speed)


def render(job, mode="preview", retry=False):
    require(mode in ("rough","preview","draft","final"), "render_mode", "Use rough, preview, draft or final")
    with job_lock(job):
        job, p = load_job(job)
        source_path(job, p)
        plan = p.get("plan")
        require(plan, "plan_required", "Apply an audited plan before rendering")
        rough_basis = None
        if mode == "rough":
            from .workflow import structure_fingerprint, rough_view
            rough_basis = structure_fingerprint(p)
            p = rough_view(p)
            plan = p["plan"]
        t = transcript(job,p)
        clips = validate_plan(plan, p["source"]["duration"], t["words"], p["assets"])
        semantic = plan.get("semantic_review", {})
        require(semantic.get("status") == "reviewed" and semantic.get("evidence"),
                "semantic_review_required", "Agent must review original words/context and record its edit rationale")
        if mode == "final" and not p["fixture"]:
            require((p.get("style_approval") or {}).get("style_hash") == style_hash(plan), "style_confirmation_required", "First real style sample needs user confirmation; render preview first")
            from .workflow import require_editorial_ready
            require_editorial_ready(job)
            from .workflow import require_source_ready
            require_source_ready(job)
        if mode == "final" and plan.get("sound_effects"):
            require(plan.get("sfx_review", {}).get("listened") is True and plan.get("sfx_review", {}).get("evidence"), "sfx_listening_pending", "SFX listening review is pending; export a draft")
        if mode == "final" and plan.get("music_asset_id"):
            require(p["assets"][plan["music_asset_id"]].get("review",{}).get("status") != "technical_only", "music_listening_pending", "Music listening review is pending; export a draft")
        formats = output_formats(plan, p["source"]["probe"])
        selected_ids = {o["asset_id"] for o in plan.get("overlays", []) if o.get("asset_id")}
        if plan.get("music_asset_id"):
            selected_ids.add(plan["music_asset_id"])
        if plan.get("ending"):
            selected_ids.add(plan["ending"]["asset_id"])
        for aid in selected_ids:
            asset = p["assets"][aid]
            require(file_hash(inside(job,asset["path"])) == asset["sha256"], "asset_changed", "Selected asset bytes changed")
        if mode == "preview":
            clips = preview_plan(plan["clips"], t["words"], speed=plan.get("style",{}).get("playback_speed",1))
        style = {**DEFAULT_STYLE, **plan.get("style",{})}
        words = mapped_words(t["words"], clips, plan.get("caption_corrections"), plan.get("caption_break_after"), plan.get("caption_groups"))
        scale = .5 if mode == "preview" else 1
        key = digest({"engine":__version__, "plan":plan, "source":p["source"]["sha256"], "transcript":p["transcript"]["sha256"],
                      "assets":p["assets"], "mode":mode, "font":file_hash(font_path())})
        work = job / "renders" / key
        work.mkdir(parents=True, exist_ok=True)
        previous = read_json(work/"render.json") if (work/"render.json").exists() else None
        if previous and previous.get("complete") and all(inside(job,r["path"]).is_file() and file_hash(inside(job,r["path"])) == r["sha256"] for r in previous["files"].values()):
            previous["revision"] = p["revision"]
            atomic_json(job/("latest-rough.json" if mode=="rough" else "latest-render.json"), previous)
            return {**previous, "reused": True}
        attempts_file = work/"attempts.json"
        attempts = read_json(attempts_file) if attempts_file.exists() else {"count":0}
        require(attempts["count"] == 0 or (retry and attempts["count"] < 2), "retry_limit", "Inspect render logs. One explicit --retry allowed per unchanged render fingerprint")
        atomic_json(attempts_file, {"count":attempts["count"]+1,"started":time.time()})
        ending_duration = round(plan.get("ending", {}).get("duration", 0)*FPS)/FPS if mode != "preview" else 0
        began = time.time()
        receipt = {"schema_version":1,"complete":False,"fixture":p["fixture"],"revision":p["revision"],
                   "fingerprint":key,"mode":mode,"requested_formats":list(formats),"playback_speed":plan.get("style",{}).get("playback_speed",1),"files":{},"review_status":"pending","clips":clips,
                   "expected_duration":sum(c["output_duration"] for c in clips)+ending_duration, "ending_duration":ending_duration, "cached_clips":0}
        if rough_basis:
            receipt["structure_fingerprint"] = rough_basis
            receipt["review_status"] = "unverified"
        atomic_json(work/"render.json",receipt)
        try:
            audio, audio_reused = render_audio(job,p,clips,style)
            receipt["audio_reused"] = audio_reused
            audio = finish_audio(job, plan, clips, audio, work, ending_duration, ff, music=p["assets"].get(plan.get("music_asset_id")))
            atomic_json(work/"visual-rhythm.json", rhythm_report(plan,clips,include_ending=bool(ending_duration)))
            for aspect, dimensions in formats.items():
                variant = work/aspect
                variant.mkdir(exist_ok=True)
                parts = []
                for c in clips:
                    path,cached = render_clip(job,p,c,[] if mode=="rough" else words,aspect,style,scale,dimensions,include_ending=bool(ending_duration))
                    parts.append(path)
                    receipt["cached_clips"] += int(cached)
                if ending_duration:
                    parts.append(render_ending(job,{**plan,"_ending_asset":p["assets"][plan["ending"]["asset_id"]]},variant,dimensions,scale,ff))
                video = variant/"video-only.mp4"
                concatenate(parts,video,variant)
                target = variant/(mode+".mp4")
                ff(["-i",video,"-i",audio,"-map","0:v:0","-map","1:a:0","-c:v","copy",
                    "-af",f"volume={style.get('encode_headroom_db',0)}dB",
                    "-c:a","aac","-b:a","192k","-ar","48000","-movflags","+faststart","-video_track_timescale","90000","-movie_timescale","90000",
                    "-t",receipt["expected_duration"],target],variant,"mux")
                width,height = [round(v*scale/2)*2 for v in dimensions]
                cues = caption_cues(words,width,height,style,scale)
                themes=global_caption_themes(plan,clips)
                write_captions(variant,cues,width,height,style,scale,theme_ranges=themes)
                global_effects = []
                for c in clips:
                    for effect in plan.get("visual_effects", []):
                        if effect["clip_id"] == c["id"] and effect["offset"] < c["end"]-c["start"]:
                            global_effects.append({**effect,"offset":c["output_start"]+effect["offset"]/c["playback_speed"],"duration":min(effect["duration"]/c["playback_speed"],c["output_duration"]-effect["offset"]/c["playback_speed"])})
                append_keywords(variant/"captions.ass",global_effects,1,width,height,scale)
                atomic_json(variant/"captions.json",cues)
                from .workflow import caption_readability
                atomic_json(variant/"caption-readability.json",caption_readability(cues))
                receipt["files"][aspect] = {"path":target.relative_to(job).as_posix(),"sha256":file_hash(target),
                    "width":width,"height":height,"subtitles":(variant/"captions.srt").relative_to(job).as_posix()}
                atomic_json(work/"render.json",receipt)
            receipt.update(complete=True,elapsed_seconds=round(time.time()-began,2))
            atomic_json(work/"render.json",receipt)
            atomic_json(job/("latest-rough.json" if mode=="rough" else "latest-render.json"),receipt)
            return receipt
        except Exception as e:
            receipt["error"] = {"type":type(e).__name__,"message":str(e)}
            atomic_json(work/"render.json",receipt)
            raise
